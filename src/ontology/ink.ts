/** 글자색으로 쓸 때만 통과시킨다. 모르는 색은 그대로 둔다 — 임의로 손대면 더 나빠진다. */
export function ink(c: string | undefined | null): string | undefined {
  if (!c) return c ?? undefined
  if (getTheme() !== 'light') return c
  return LIGHT[c.toLowerCase()] ?? c
}
