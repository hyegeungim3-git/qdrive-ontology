/**
 * 세 가지 목적 — **누가 이 데이터로 무엇을 결정하는가.**
 *
 * 온톨로지는 그 자체로 값어치가 없다. 누군가 그걸로 **결정을 내릴 때** 값어치가 생긴다.
 * 이 도구가 답해야 하는 결정은 셋이다.
 *
 *  1. **대구시 — 정책 수립**: 어느 노선을 늘리고 줄이나. 재정지원금이 맞게 나갔나.
 *  2. **기사·운송사 — 안전 운전**: 왜 감점됐고 무엇을 바꾸면 되나. 오늘 누가 위험한가.
 *  3. **탄소중립**: 얼마나 줄였나. 그 숫자를 남이 믿을 수 있나.
 *
 * 각 결정마다 **무엇을 묻는지 · 어느 데이터가 답하는지 · 지금 답할 수 있는지**를 적는다.
 * 「지금 못 한다」를 적는 것이 이 표의 값어치다 — 못 하는 이유가 데이터가 없어서인지,
 * 규칙이 없어서인지, 원천이 없어서인지가 다르기 때문이다.
 */

