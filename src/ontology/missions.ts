export const missionOf = (id: MissionId) => MISSIONS.find((m) => m.id === id) ?? MISSIONS[0]

export const READY_TONE: Record<Ready, string> = {
  답한다: '#34d399',
  부분: '#fbbf24',
  '못 한다': '#64748b',
}

export function missionStats() {
  const qs = MISSIONS.flatMap((m) => m.questions)
  return {
    missions: MISSIONS.length,
    questions: qs.length,
    ready: qs.filter((q) => q.ready === '답한다').length,
    partial: qs.filter((q) => q.ready === '부분').length,
    no: qs.filter((q) => q.ready === '못 한다').length,
  }
}
