export const PROD_GROUPS = ['규모', '검증', '저장', '권한', '식별', '원천', 'AI 활용'] as const

/** 제안서 첨부용 — 화면과 같은 정의를 읽는다 */
export function buildProductionMap(): string {
  const L: string[] = [
    '# Qdrive 온톨로지 — 데모 ↔ 실서비스 대응표',
    '',
    '이 도구는 브라우저 안에서 온톨로지 위에 서비스를 돌립니다. 실서비스와 **규모는 다르지만 순서는 같습니다** —',
    '들어올 때 검증하고, 걸리면 격리하고, 통과분만 하류로 내려보내고, 규칙을 고치려면 문법을 발행합니다.',
    '',
    '다만 **규모만 다른 것이 아닌 항목**은 표에 ⚠로 표시했습니다. 숨기지 않는 편이 검토에 도움이 됩니다.',
    '',
  ]
  PROD_GROUPS.forEach((g) => {
    const rows = PROD_MAP.filter((r) => r.group === g)
    if (!rows.length) return
    L.push(`## ${g}`, '')
    L.push('| 항목 | 데모에서는 | 실서비스에서는 | 전제 · 주의 |', '|---|---|---|---|')
    rows.forEach((r) => L.push(`| ${r.differs ? '⚠ ' : ''}${r.item} | ${r.demo} | ${r.prod} | ${r.need} |`))
    L.push('')
  })
  L.push('## 방식 자체가 달라지는 항목', '')
  PROD_MAP.filter((r) => r.differs).forEach((r) => {
    L.push(`- **${r.item}** — ${r.need}`)
  })
  L.push('')
  L.push('## 이 데모가 이미 증명한 것', '')
  L.push('- 적재 게이트가 **실제로** 하류를 막는다 — 결함을 켜면 집계 숫자가 줄어든다')
  L.push('- 안전점수를 **개념 스페이스의 감점 가중치**로 그래프를 순회해 계산한다')
  L.push('- 근거 사슬이 **문법이 허용한 관계만** 따라 걷는다 — 문법을 발행하면 사슬이 달라진다')
  L.push('- 규정이 **화면을 실제로 막는다** — 역할을 바꾸면 실명이 가명키로, 차량 범위가 좁아진다')
  L.push('- 레코드마다 **어느 문법으로 검증됐는지** 스탬프가 붙고, 소급은 결정이다')
  return L.join('\n')
}
